// Build the single-file Cloudflare Worker bundle from the shared core.
//
// The translation logic lives once, in the plugin's `src/`. This script bundles
// `src/worker-entry.mjs` (the Worker-specific HTTP shell) plus the core modules
// it imports into one minified ESM file, `worker.js`, that `wrangler` deploys.
//
//   node scripts/build.mjs          # write worker.js
//   node scripts/build.mjs --check  # fail if worker.js is stale

import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const workerDir = path.resolve(here, "..");
const entry = path.join(workerDir, "src", "worker-entry.mjs");
const outfile = path.join(workerDir, "worker.js");

const result = await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  minify: true,
  legalComments: "none",
  banner: {
    js: "// Generated by worker/scripts/build.mjs from the shared core in ../src — do not edit by hand.",
  },
  metafile: true,
  write: false,
});

const output = result.outputFiles[0].text;

if (output.includes("node:")) {
  const offenders = [...new Set(output.match(/node:[a-z_/]+/g))];
  throw new Error(`The bundle must stay runtime-agnostic, but it references: ${offenders.join(", ")}`);
}

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(outfile, "utf8");
  } catch {
    current = "";
  }
  if (current !== output) {
    console.error("worker.js is stale — run `node scripts/build.mjs` and commit the result.");
    process.exit(1);
  }
  console.log(`worker.js is up to date (${Buffer.byteLength(output)} bytes).`);
} else {
  await writeFile(outfile, output);
  console.log(`Wrote worker.js (${Buffer.byteLength(output)} bytes).`);
}
